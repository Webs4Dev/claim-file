"""Submit the sample claims through the running API and check outcomes.

Start Redis and the API first:

    docker compose up -d
    venv/bin/uvicorn app.main:app

Then, from the project root:

    venv/bin/python -m tests.run_test_claims            # all claims
    venv/bin/python -m tests.run_test_claims claim_005  # names containing this

Claims are generated by scripts/make_test_claims.py. Exits non-zero if
any claim ends outside its expected outcome.
"""

import json
import sys
import time
from pathlib import Path

import httpx


API_BASE = "http://127.0.0.1:8000"

SAMPLE_DIRECTORY = Path("data/sample_claims")

RUNNING_STATUSES = {"pending", "in_progress"}

POLL_SECONDS = 3

TIMEOUT_SECONDS = 300


# claim_001 predates the generator and has no claim.json.
CLAIM_001 = {
    "purpose": "Original baseline claim. Should reach human approval.",
    "expected_status": ["human_approval"],
    "files": {
        "policy_schedule": "policy_schedule.pdf",
        "vehicle_registration": "vehicle_registration.pdf",
        "driving_license": "driving_licence.pdf",
        "damage_survey_report": "damage_survey_report.pdf",
        "repair_estimate": "repair_estimate.pdf",
    },
}


def load_claims(name_filter: str | None) -> list[tuple[str, dict]]:
    claims = []

    for directory in sorted(SAMPLE_DIRECTORY.iterdir()):
        if not directory.is_dir():
            continue

        if name_filter and name_filter not in directory.name:
            continue

        spec_path = directory / "claim.json"

        if spec_path.exists():
            spec = json.loads(spec_path.read_text(encoding="utf-8"))
            spec["files"] = {
                document_type: f"{document_type}.pdf"
                for document_type in spec["documents"]
            }
        elif directory.name == "claim_001":
            from tests.test_pipeline import CLAIM_FORM

            spec = {
                **CLAIM_001,
                "claim_form": CLAIM_FORM.model_dump(),
            }
        else:
            continue

        spec["directory"] = directory
        claims.append((directory.name, spec))

    return claims


def submit_claim(client: httpx.Client, spec: dict) -> str:
    handles = {
        document_type: open(spec["directory"] / file_name, "rb")
        for document_type, file_name in spec["files"].items()
    }

    try:
        response = client.post(
            "/claims",
            data={"claim_form": json.dumps(spec["claim_form"])},
            files={
                document_type: (handle.name, handle, "application/pdf")
                for document_type, handle in handles.items()
            },
        )
    finally:
        for handle in handles.values():
            handle.close()

    response.raise_for_status()

    return response.json()["claim_id"]


def wait_for_claim(client: httpx.Client, claim_id: str) -> dict:
    deadline = time.monotonic() + TIMEOUT_SECONDS

    while True:
        claim = client.get(f"/claims/{claim_id}").json()

        if claim["status"] not in RUNNING_STATUSES:
            return claim

        if time.monotonic() > deadline:
            return claim

        time.sleep(POLL_SECONDS)


def check_claim(spec: dict, claim: dict) -> list[str]:
    problems = []
    review = claim.get("review") or {}

    if (
        spec.get("expected_status")
        and claim["status"] not in spec["expected_status"]
    ):
        problems.append(
            f"status {claim['status']!r}, expected one of "
            f"{spec['expected_status']}"
        )

    if (
        spec.get("expected_review")
        and review.get("status") not in spec["expected_review"]
    ):
        problems.append(
            f"review {review.get('status')!r}, expected one of "
            f"{spec['expected_review']}"
        )

    if spec.get("expected_pending"):
        pending = {
            document["document_type"]
            for document in claim["pending_documents"]
        }
        missing = set(spec["expected_pending"]) - pending

        if missing:
            problems.append(f"pending documents missing {sorted(missing)}")

    return problems


def print_claim(name: str, spec: dict, claim: dict, problems: list[str]) -> None:
    investigation = claim.get("investigation") or {}
    review = claim.get("review") or {}

    print(f"\n{'=' * 78}\n{name}  [{'FAIL' if problems else 'PASS'}]")
    print(f"  purpose:  {spec['purpose']}")
    print(f"  claim_id: {claim['claim_id']}")
    print(
        f"  status:   {claim['status']}  |  investigation: "
        f"{investigation.get('overall_status')}  |  review: "
        f"{review.get('status')}"
    )

    for finding in investigation.get("findings", []):
        if finding["status"] != "VALID":
            print(f"  - {finding['category']}: {finding['status']} - {finding['finding']}")

    if review.get("summary"):
        print(f"  review summary: {review['summary']}")

    if claim["pending_documents"]:
        print(
            "  pending documents: "
            + ", ".join(d["document_type"] for d in claim["pending_documents"])
        )

    for problem in problems:
        print(f"  !! {problem}")


def main() -> int:
    name_filter = sys.argv[1] if len(sys.argv) > 1 else None
    claims = load_claims(name_filter)

    if not claims:
        print("No sample claims found. Run: python -m scripts.make_test_claims")
        return 1

    failures = 0

    with httpx.Client(base_url=API_BASE, timeout=60) as client:
        client.get("/health").raise_for_status()

        submitted = [
            (name, spec, submit_claim(client, spec))
            for name, spec in claims
        ]

        print(f"Submitted {len(submitted)} claims; waiting for results...")

        for name, spec, claim_id in submitted:
            claim = wait_for_claim(client, claim_id)
            problems = check_claim(spec, claim)
            failures += bool(problems)
            print_claim(name, spec, claim, problems)

    print(f"\n{len(submitted) - failures}/{len(submitted)} claims as expected.")

    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
